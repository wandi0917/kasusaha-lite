-- Add per-business barcode values to the existing store product catalog.
-- Existing product_code and all transaction RPCs remain unchanged.
alter table public.store_products
  add column if not exists barcode_value text,
  add column if not exists barcode_type text not null default 'custom';

alter table public.store_products
  drop constraint if exists store_products_barcode_type_check;

alter table public.store_products
  add constraint store_products_barcode_type_check
  check (barcode_type in ('custom','factory'));

create unique index if not exists store_products_business_barcode_unique
  on public.store_products (business_id, barcode_value)
  where barcode_value is not null and btrim(barcode_value) <> '';

comment on column public.store_products.barcode_value is
  'Barcode value used by camera and HID/Bluetooth scanners; may be a factory GTIN or KasUsaha custom Code 128 value.';
comment on column public.store_products.barcode_type is
  'custom = generated by KasUsaha Lite; factory = barcode printed by product manufacturer.';

-- Give existing products a unique custom Code 128 barcode without changing their SKU,
-- prices, stock, ownership, or historical sales.
update public.store_products
set barcode_value = 'KS' || upper(substr(replace(id::text, '-', ''), 1, 12)),
    barcode_type = 'custom'
where barcode_value is null or btrim(barcode_value) = '';
